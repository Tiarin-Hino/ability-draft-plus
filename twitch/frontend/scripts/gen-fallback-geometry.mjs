#!/usr/bin/env node
// Generates src/geometry/fallback-1080p.ts from the app's 1920x1080 layout preset
// (resources/config/layout_coordinates.json). Used when the rich state carries no
// geometry (older app) — the board is assumed to fill a 16:9 frame.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const layoutPath = resolve(__dirname, '../../../resources/config/layout_coordinates.json')
const outPath = resolve(__dirname, '../src/geometry/fallback-1080p.ts')

const W = 1920
const H = 1080
const layout = JSON.parse(readFileSync(layoutPath, 'utf-8')).resolutions['1920x1080']
const r = (v) => Math.round(v * 10000) / 10000
const rect = (c, params) => [
  r(c.x / W),
  r(c.y / H),
  r((c.width > 0 ? c.width : params.width) / W),
  r((c.height > 0 ? c.height : params.height) / H),
]

const pool = Array.from({ length: 48 }, () => null)
for (const c of layout.ultimate_slots_coords) pool[c.hero_order * 4] = rect(c, { width: 0, height: 0 })
for (const c of layout.standard_slots_coords) pool[c.hero_order * 4 + c.ability_order] = rect(c, { width: 0, height: 0 })

const models = Array.from({ length: 12 }, () => null)
for (const c of layout.models_coords ?? []) models[c.hero_order] = rect(c, { width: 0, height: 0 })

const cards = Array.from({ length: 10 }, () => null)
for (const c of layout.heroes_coords ?? []) cards[c.hero_order] = rect(c, layout.heroes_params)

const picks = Array.from({ length: 40 }, () => null)
const nextBox = new Map()
for (const c of layout.selected_abilities_coords ?? []) {
  const box = c.is_ultimate ? 3 : nextBox.get(c.hero_order) ?? 0
  if (!c.is_ultimate) nextBox.set(c.hero_order, box + 1)
  picks[c.hero_order * 4 + box] = rect(c, layout.selected_abilities_params)
}

const body = `// GENERATED by scripts/gen-fallback-geometry.mjs from resources/config/layout_coordinates.json
// (1920x1080 preset). Do not edit by hand — re-run \`npm run gen:geometry\`.
import type { TwitchRichGeometry } from '@shared/types/twitch'

export const FALLBACK_FRAME = { w: ${W}, h: ${H} } as const

export const FALLBACK_1080P: TwitchRichGeometry = ${JSON.stringify({ pool, models, cards, picks })}
`
writeFileSync(outPath, body)
console.log(`Wrote ${outPath}`)
